"""Calibrated NO-TOOL abstention head — the Step-2 fix for the 0.51 keep.

All four 2026-05-21 deep-research reports converged on the same diagnosis:
the router's weak spot is not tool recall (0.83, already good) but NO-TOOL
abstention (0.51, barely a coin flip). The root cause is structural — today
abstention is a *residual* (we abstain only when every other layer happens to
miss), never a *positively-scored decision*. A single cosine/centroid threshold
can't fix it because raw cosine is not comparable across queries (e5/MiniLM
crush absolute magnitudes; the same 0.45 means different things for "mutea" vs
"qué tiempo hace mañana").

The fix the literature prescribes (DETER arXiv:2405.19967, DROID
arXiv:2510.14110, selective-classification + temperature-scaling): make
abstention a CALIBRATED classifier over cheap, query-comparable features, and
use it as a reject option with a controlled risk. We compute a small feature
vector at routing time (intent-centroid scores + semantic-cosine shape + query
length + keyword-fired flag), feed a logistic regression trained OFFLINE on the
dev split ONLY, and abstain when P(no_tool) clears a calibrated threshold.

Reproducibility (project law): the weights live in a versioned JSON
(`data/abstain_head.json`), regenerated by `scripts/train_abstain_head.py`. No
pickle, no binary artifact, no sklearn at runtime — just a numpy dot product, so
the forward pass is sub-millisecond and dependency-light.

Anti-overfit: the trainer reads the SAME stable-hash dev/holdout split as
router_eval.py and is forbidden from touching holdout rows. The threshold is
chosen on a dev-internal CV fold, never on holdout.
"""
from __future__ import annotations

import json
import math
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

_ROOT = Path(__file__).resolve().parent.parent.parent  # reorg 2026-05-28: safety_pkg/ -> +1 nivel
_WEIGHTS_PATH = _ROOT / "gemma4_agent" / "data" / "abstain_head.json"

# Feature names in a FIXED order — the trainer and the runtime must agree on
# this vector exactly. Adding a feature means retraining (bump model_version).
FEATURE_NAMES: tuple[str, ...] = (
    "intent_info",        # cosine to info centroid
    "intent_action",      # cosine to action centroid
    "intent_chitchat",    # cosine to chitchat centroid
    "intent_selfref",     # cosine to self-reference centroid
    "intent_meta",        # cosine to meta-directive centroid
    "conv_minus_world",   # max(chitchat,selfref,meta) - max(action,info)
    "sem_top1",           # top-1 semantic cosine (tool descriptions)
    "sem_top3_mean",      # mean of top-3 semantic cosines
    "sem_gap_1_3",        # sem_top1 - sem_top3_mean (peakedness)
    "word_count_norm",    # min(words,12)/12
    "is_question",        # 1.0 if '?' / '¿' present
    "keyword_fired",      # 1.0 if the keyword router proposed any tool
)


@dataclass
class AbstainModel:
    weights: list[float]
    bias: float
    threshold: float
    feature_names: tuple[str, ...]
    model_version: str = "v1"
    # Umbral POR IDIOMA (auditoría §7.5; CausalAbstain arXiv:2506.00519, MKA
    # arXiv:2503.23687): los embeddings multilingües tienen escalas distintas por
    # idioma, así que un único umbral global discrimina mal a los de bajo recurso.
    # {lang_code: threshold}. VACÍO por defecto -> usa el global (cero regresión).
    # Se llena cuando router_eval.py calibre por idioma sobre el dev split.
    thresholds_by_lang: dict[str, float] = field(default_factory=dict)

    def p_no_tool(self, feats: dict[str, float]) -> float:
        z = self.bias
        for w, name in zip(self.weights, self.feature_names):
            z += w * float(feats.get(name, 0.0))
        return 1.0 / (1.0 + math.exp(-z))

    def threshold_for(self, lang: str | None = None) -> float:
        """Umbral para el idioma dado; cae al global si no hay calibración propia.
        Universal: nunca rompe (lang None / desconocido -> global)."""
        if lang:
            t = self.thresholds_by_lang.get(lang.strip().lower())
            if t is not None:
                return float(t)
        return self.threshold

    def should_abstain(self, feats: dict[str, float], lang: str | None = None) -> bool:
        return self.p_no_tool(feats) >= self.threshold_for(lang)


_MODEL: AbstainModel | None = None
_LOAD_TRIED = False
# Serializes load_model: warmup thread + first turn both call it. The artifact
# is a small JSON so a double-parse is cheap, but the lock keeps _LOAD_TRIED and
# _MODEL consistent under contention. Double-checked locking.
import threading as _threading
_LOAD_LOCK = _threading.Lock()


def is_enabled() -> bool:
    """On when a trained artifact exists. Disable with GEMMA4_ABSTAIN_HEAD=0."""
    raw = (os.environ.get("GEMMA4_ABSTAIN_HEAD") or "").strip().casefold()
    if raw in {"0", "false", "no", "off"}:
        return False
    return True


def load_model() -> AbstainModel | None:
    global _MODEL, _LOAD_TRIED
    if _MODEL is not None:
        return _MODEL
    if _LOAD_TRIED:
        return None
    with _LOAD_LOCK:
        if _MODEL is not None:
            return _MODEL
        if _LOAD_TRIED:
            return None
        return _load_model_locked()


def _load_model_locked() -> AbstainModel | None:
    global _MODEL, _LOAD_TRIED
    _LOAD_TRIED = True
    if not _WEIGHTS_PATH.exists():
        return None
    try:
        d = json.loads(_WEIGHTS_PATH.read_text(encoding="utf-8"))
        # thresholds_by_lang: opcional en el JSON; si no está, queda vacío y se usa
        # el threshold global (retrocompat total con artefactos viejos).
        _tbl_raw = d.get("thresholds_by_lang") or {}
        _tbl = {str(k).lower(): float(v) for k, v in _tbl_raw.items()} if isinstance(_tbl_raw, dict) else {}
        _MODEL = AbstainModel(
            weights=[float(x) for x in d["weights"]],
            bias=float(d["bias"]),
            threshold=float(d["threshold"]),
            feature_names=tuple(d["feature_names"]),
            model_version=str(d.get("model_version", "v1")),
            thresholds_by_lang=_tbl,
        )
        # Guard: feature order must match this module's expectation, or the
        # dot product would silently mix up coefficients.
        if _MODEL.feature_names != FEATURE_NAMES:
            _MODEL = None
            return None
        return _MODEL
    except Exception:
        return None


def build_features(
    text: str,
    *,
    intent: Any | None,
    scored: list[tuple[str, float]] | None,
    keyword_fired: bool,
) -> dict[str, float]:
    """Assemble the fixed feature vector. `intent` is an IntentScores (or None),
    `scored` is suggest_tools_scored() output (tool, cosine) sorted desc."""
    info = action = chitchat = selfref = meta = 0.0
    if intent is not None:
        info = float(getattr(intent, "info", 0.0))
        action = float(getattr(intent, "action", 0.0))
        chitchat = float(getattr(intent, "chitchat", 0.0))
        selfref = float(getattr(intent, "selfref", 0.0))
        meta = float(getattr(intent, "meta", 0.0))
    conv_minus_world = max(chitchat, selfref, meta) - max(action, info)

    cos = [s for _, s in (scored or [])]
    top1 = cos[0] if cos else 0.0
    top3 = cos[:3]
    top3_mean = sum(top3) / len(top3) if top3 else 0.0
    gap = top1 - top3_mean

    words = len(text.split())
    return {
        "intent_info": info,
        "intent_action": action,
        "intent_chitchat": chitchat,
        "intent_selfref": selfref,
        "intent_meta": meta,
        "conv_minus_world": conv_minus_world,
        "sem_top1": top1,
        "sem_top3_mean": top3_mean,
        "sem_gap_1_3": gap,
        "word_count_norm": min(words, 12) / 12.0,
        "is_question": 1.0 if ("?" in text or "¿" in text) else 0.0,
        "keyword_fired": 1.0 if keyword_fired else 0.0,
    }
