        private int _settleReads;

        public IWindowEventWatch? WatchWindowEvents(IReadOnlyCollection<int> processes)
        {
            if (WindowEvents is { } events)
                events.Family = processes;
            return WindowEvents;
        }

        public bool IsMainWindow(long windowHandle) => MainWindows.Contains(windowHandle);

        private void SettleRead()
        {
            if (!_settling || _newDocumentIssued)
                return;
            _settleReads++;
            if (LateBorn is { } late && _settleReads == LateBornAtRead)
                Observations = [.. Observations, late];
            if (BornAtEveryRead)
                Observations = [.. Observations, Observation(foreground: false) with { WindowHandle = 1000 + _settleReads }];
        }

        public string WindowTitle(long windowHandle)
        {
            _settling |= ActivateCalls > 0;
            if (!_bornAfterStart && BornAfterStart is { } born && ActivateCalls > 0)
            {
                _bornAfterStart = true;
                Observations = [.. Observations, born];
            }

            return !Titles.TryGetValue(windowHandle, out string? title) ? string.Empty
                : TitleDrifts ? $"{title} {++_titleReads}"
                : title;
        }

        public bool IsOwnedWindow(long windowHandle) => Owned.Contains(windowHandle);

        public int WindowProcessId(long windowHandle) => windowHandle switch { 73 => 4242, 74 => 5151, _ => 0 };

        public bool SameApplication(int opened, int process) =>
            opened > 0 && (opened == process || SiblingIsSameApplication && process == 5151);

        public bool FrontGuardInterrupted(ForegroundHandBack.GuardStamp stamp) => GuardInterrupted;

        public bool ReturnForeground(long previous, long opened)
        {
            HandedBack.Add(previous);
            _frontBack = HandBackHolds && HandedBack.Count > RetakesAfterHandBack;
            return HandBackHolds;
        }

        public int ActivateCalls { get; private set; }

        // Renew al máximo (velocidad): Windows shows a frame of the application with nothing of it inside, and how many
        // times the opening asked.
        public bool EmptyFrameShown { get; init; }

        public int EmptyFrameAsked { get; private set; }

        public bool ShowsEmptyFrame(InstalledApplicationEntry entry)
        {
            EmptyFrameAsked++;
            return EmptyFrameShown;
        }

        public int FocusCalls { get; private set; }

        public int DelayCalls { get; private set; }

        public Exception? CatalogFailure { get; init; }

        public Exception? InventoryFailure { get; init; }

        // Renew al máximo (6.6): the catalog Windows lists now, how many reads were asked, from which read on each one
        // waits until the test releases it, and what happened in which order.
        public IReadOnlyList<InstalledApplicationEntry> CatalogNow { get; set; } = catalog;

        public int CatalogReads { get; private set; }

        public int CatalogReadsHeldFrom { get; init; } = int.MaxValue;

        public TaskCompletionSource CatalogReleased { get; } = new(TaskCreationOptions.RunContinuationsAsynchronously);

        private readonly List<string> _events = [];

        public IReadOnlyList<string> Events
        {
            get
            {
                lock (_events)
                    return [.. _events];
            }
        }

        public void Note(string happened)
        {
            lock (_events)
                _events.Add(happened);
        }

        public ValueTask<IReadOnlyList<InstalledApplicationEntry>> ReadCatalogAsync(
            CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (CatalogFailure is not null)
            {
                return ValueTask.FromException<IReadOnlyList<InstalledApplicationEntry>>(
                    CatalogFailure);
            }

            int read = ++CatalogReads;
            Note($"catalog {read} started");
            if (read >= CatalogReadsHeldFrom)
            {
                return new(HeldReadAsync(read, cancellationToken));
            }

            Note($"catalog {read} read");
            return ValueTask.FromResult(CatalogNow);
        }

        private async Task<IReadOnlyList<InstalledApplicationEntry>> HeldReadAsync(
            int read,
            CancellationToken cancellationToken)
        {
            await CatalogReleased.Task.WaitAsync(cancellationToken).ConfigureAwait(false);
            Note($"catalog {read} read");
            return CatalogNow;
        }

        // Renew al máximo (B-APP-11): the windows the application had close right after the first inventory, before
        // anything is launched (the person closed the window BAXY was about to reuse).
        public bool WindowsGoneAfterFirstInventory { get; init; }

        private int _inventoryReads;

        public IReadOnlyList<InstalledApplicationObservation> Inventory(InstalledApplicationEntry entry)
        {
            if (InventoryFailure is not null)
                throw InventoryFailure;
            if (WindowsGoneAfterFirstInventory && _inventoryReads++ > 0 && ActivateCalls == 0)
                Observations = [];
            SettleRead();
            return Observations;
        }

        // The window status reads the strict inventory (ronda final 9); this fake's inventory is complete or fails.
        public IReadOnlyList<InstalledApplicationObservation> InventoryForWindowResolution(
            InstalledApplicationEntry entry,
            CancellationToken cancellationToken) => Inventory(entry);

        public List<bool> ActivatedForControl { get; } = [];

        // The processes that run as administrator and whose program would open again with the person's rights.
        public HashSet<int> RaisedReopenable { get; init; } = [];

        public bool RaisedButReopensUnraised(int processId) => RaisedReopenable.Contains(processId);

        public bool Activate(InstalledApplicationEntry entry, bool forControl)
        {
            ActivatedForControl.Add(forControl);
            return Activate(entry);
        }

        public bool Activate(InstalledApplicationEntry entry)
        {
            ActivateCalls++;
            if (ObservationAfterActivation is not null)
            {
                Observations = [ObservationAfterActivation];
            }

            if (LaunchedWindow is not null)
            {
                Observations = [.. Observations, LaunchedWindow];
            }

            return true;
        }

        // Auditoría D6: the window a launch shows beside the ones the application already had.
        public InstalledApplicationObservation? LaunchedWindow { get; init; }

        // Renew al máximo (B-APP-11): past this many front requests, one never answers (a window whose thread hangs)
        // until the test releases it.
        public int ForegroundHangsAfter { get; init; } = int.MaxValue;

        public ManualResetEventSlim ForegroundReleased { get; } = new(false);

        public void RequestForeground(long windowHandle)
        {
            FocusCalls++;
            if (FocusCalls > ForegroundHangsAfter)
            {
                ForegroundReleased.Wait();
            }

            _requestedForegroundHandle = windowHandle;
            if (!FocusRequiresDelay)
            {
                MarkForeground(windowHandle);
            }
        }

        // Renew al máximo (rendimiento): the waits asked before the New command was sent.
        public List<TimeSpan> DelaysBeforeNewDocument { get; } = [];

        // Renew al máximo (rendimiento): the waits asked once the New command was sent (the looks for its document).
        public List<TimeSpan> DelaysAfterNewDocument { get; } = [];

        public ValueTask DelayAsync(TimeSpan delay, CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            DelayCalls++;
            if (!_newDocumentIssued)
                DelaysBeforeNewDocument.Add(delay);
            else
                DelaysAfterNewDocument.Add(delay);
            if (FocusRequiresDelay && _requestedForegroundHandle is long windowHandle)
            {
                MarkForeground(windowHandle);
            }
            return ValueTask.CompletedTask;
        }

        private void MarkForeground(long windowHandle)
        {
            Observations = Observations
                .Select(item => item.WindowHandle == windowHandle
                    ? item with { Foreground = true }
                    : item)
                .ToArray();
        }
